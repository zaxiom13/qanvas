function runLocalStatementsDisplay(statements: string[], expression: string): string {
  const session = createSession();
  for (const statement of statements) {
    session.evaluate(statement);
  }
  return formatValue(session.evaluate(expression).value);
}

function createRng(seed: number) {
  let state = seed >>> 0;
  return () => {
    state = (1664525 * state + 1013904223) >>> 0;
    return state / 0x1_0000_0000;
  };
}

function randomInt(next: () => number, min: number, max: number) {
  return Math.floor(next() * (max - min + 1)) + min;
}

function randomVector(next: () => number, minLength = 2, maxLength = 7) {
  const length = randomInt(next, minLength, maxLength);
  return Array.from({ length }, () => randomInt(next, -9, 9));
}

function vectorLiteral(values: number[]) {
  return values.join(" ");
}

function generatedCases() {
  const next = createRng(0x5eeded);
  const cases: string[] = [];

  for (let index = 0; index < 20; index += 1) {
    const left = randomInt(next, -20, 20);
    const right = randomInt(next, -20, 20) || 1;
    cases.push(`(${left}+${right})*${randomInt(next, -5, 5)}`);
    cases.push(`${left} div ${right}`);
    cases.push(`${left} mod ${right}`);
  }

  for (let index = 0; index < 25; index += 1) {
    const values = randomVector(next);
    const literal = vectorLiteral(values);
    const take = randomInt(next, -values.length - 2, values.length + 2);
    const drop = randomInt(next, -values.length, values.length);
    const rotate = randomInt(next, -values.length * 2, values.length * 2);
    cases.push(`sum ${literal}`);
    cases.push(`(+\\) ${literal}`);
    cases.push(`reverse ${literal}`);
    cases.push(`${take}#${literal}`);
    cases.push(`${drop}_${literal}`);
    cases.push(`${rotate} rotate ${literal}`);
    cases.push(`distinct ${literal}`);
  }

  return cases;
}

