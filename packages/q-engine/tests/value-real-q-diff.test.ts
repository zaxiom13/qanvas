const Q_BIN = process.env.QANVAS_Q_BIN || `${process.env.HOME}/.kx/bin/q`;
const hasRealQ = existsSync(Q_BIN);

const qString = (source: string) =>
  `"${source.replaceAll("\\", "\\\\").replaceAll('"', '\\"').replaceAll("\n", "\\n")}"`;

const normalizeDisplay = (text: string) =>
  text
    .replace(/\n+$/, "\n")
    .split("\n")
    .map((line) => {
      const trimmed = line.trimEnd();
      return /^[-| ]+$/.test(trimmed) ? trimmed.replace(/-+/g, "-") : trimmed;
    })
    .join("\n");

function runRealQDisplay(source: string): string {
  const dir = mkdtempSync(join(tmpdir(), "qanvas-value-diff-"));
  const outputPath = join(dir, "out.txt");
  const scriptPath = join(dir, "runner.q");

  try {
    writeFileSync(
      scriptPath,
      [
        `result:value ${qString(source)}`,
        `(\`$":${outputPath}") 0: enlist .Q.s result`,
        "\\\\"
      ].join("\n"),
      "utf8"
    );

    const result = spawnSync(Q_BIN, [scriptPath], {
      cwd: dir,
      encoding: "utf8",
      env: { ...process.env, QHOME: process.env.QHOME || `${process.env.HOME}/.kx` },
      timeout: 10_000
    });

    if (result.status !== 0) {
      throw new Error(result.stderr || result.stdout || `q exited with code ${result.status}`);
    }

    return readFileSync(outputPath, "utf8");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

